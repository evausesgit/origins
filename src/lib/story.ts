/**
 * Animated stories — data model and animation maths.
 *
 * A story is a pure function of time: every frame is drawn from `t` alone, so
 * the player can play, pause, scrub and jump between chapters without any
 * state to rebuild. The voice-over is a separate track that follows `t`.
 */
import type { L, Locale } from "@/data/types";

export interface StoryCue {
  id: string;
  scene: string;
  fr: string;
  en: string;
  /** What the voice reads instead of the caption (pronunciation, years). */
  say?: Partial<Record<Locale, string>>;
}

export interface StoryScript {
  scenes: { id: string; label: L }[];
  cues: StoryCue[];
}

/** Generated by scripts/generate_story_audio.py from the measured voice-over. */
export interface StoryTiming {
  duration: number;
  scenes: Record<string, { start: number; end: number }>;
  cues: Record<string, { at: number; end: number }>;
}

export interface Story {
  slug: string;
  script: StoryScript;
  timing: StoryTiming;
}

export const clamp01 = (x: number) => (x < 0 ? 0 : x > 1 ? 1 : x);
export const lerp = (a: number, b: number, p: number) => a + (b - a) * p;
export const easeInOut = (x: number) => (x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2);
export const easeOut = (x: number) => 1 - Math.pow(1 - x, 3);
/** Overshooting ease, for stamps landing on the page. */
export const easeBack = (x: number) => 1 + 2.4 * Math.pow(x - 1, 3) + 1.4 * Math.pow(x - 1, 2);

/** Linear progress of `t` through [start, start + dur], clamped to 0..1. */
export const prog = (t: number, start: number, dur: number) => clamp01((t - start) / dur);

/** Helpers bound to one story's timing, handed to its scenes. */
export function clock(timing: StoryTiming) {
  const cue = (id: string) => {
    const c = timing.cues[id];
    if (!c) throw new Error(`Unknown story cue: ${id}`);
    return c;
  };
  return {
    /** Start of a cue. */
    at: (id: string) => cue(id).at,
    /** End of a cue (longest of its readings). */
    end: (id: string) => cue(id).end,
    /** A moment inside a cue, as a fraction of its length. */
    within: (id: string, f: number) => {
      const c = cue(id);
      return c.at + (c.end - c.at) * f;
    },
    scene: (id: string) => timing.scenes[id],
  };
}
export type Clock = ReturnType<typeof clock>;

/** The cue being read at `t` (the last one started, until the next starts). */
export function cueAt(script: StoryScript, timing: StoryTiming, t: number): StoryCue | null {
  let found: StoryCue | null = null;
  for (const c of script.cues) {
    const ct = timing.cues[c.id];
    if (ct && ct.at <= t + 0.05) found = t <= ct.end + 1.2 ? c : null;
  }
  return found;
}

export function sceneAt(script: StoryScript, timing: StoryTiming, t: number) {
  let found = script.scenes[0];
  for (const s of script.scenes) if (timing.scenes[s.id].start <= t + 0.01) found = s;
  return found;
}

/** Greedy word wrap for SVG text (no layout engine in SVG). */
export function wrap(text: string, maxChars: number): string[] {
  // French typography: « word », word ? word : stay glued to their word.
  const words: string[] = [];
  for (const w of text.split(/\s+/)) {
    if (/^[»?!:;]+$/.test(w) && words.length) words[words.length - 1] += " " + w;
    else if (words.length && words[words.length - 1] === "«") words[words.length - 1] += " " + w;
    else words.push(w);
  }
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    if (line && (line + " " + word).length > maxChars) {
      lines.push(line);
      line = word;
    } else line = line ? line + " " + word : word;
  }
  if (line) lines.push(line);
  return lines;
}
