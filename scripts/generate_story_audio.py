"""Generate a dossier's animated-story voice-over and timing, from its story.json.

    npm run story:audio -- norwich-1144

which runs:

    uv run --python 3.12 --with kokoro --with soundfile --with 'misaki[en]' --with pip \
        python scripts/generate_story_audio.py norwich-1144

Kokoro (open weights, free, runs offline once the model is cached) reads every
cue in both languages: French with `ff_siwis` (needs espeak-ng on PATH),
English with `af_heart`. The timeline is shared by both languages, so each cue
starts once the longer of its two readings of the previous cue has ended.

Writes:
  - src/data/dossiers/<slug>/story-timing.json   cue and scene times, read by the player
  - public/stories/<slug>/narration-<lang>.mp3   one silent-padded track per language

Unchanged lines are reused from ~/.cache/origins-narration. Requires ffmpeg.
"""
import hashlib
import json
import os
import pathlib
import subprocess
import sys

import numpy as np
import soundfile as sf

ROOT = pathlib.Path(__file__).resolve().parent.parent
RATE = 24000
CACHE = pathlib.Path(os.environ.get("XDG_CACHE_HOME", pathlib.Path.home() / ".cache")) / "origins-narration"


def synthesiser(spec):
    pipeline = None

    def say(text):
        nonlocal pipeline
        key = json.dumps([spec, text], sort_keys=True, ensure_ascii=False)
        hit = CACHE / (hashlib.sha256(key.encode()).hexdigest()[:24] + ".wav")
        if not hit.exists():
            if pipeline is None:
                from kokoro import KPipeline

                pipeline = KPipeline(lang_code=spec["lang"], repo_id="hexgrad/Kokoro-82M")
            parts = list(pipeline(text, voice=spec["voice"], speed=spec.get("speed", 1.0)))
            print("   ", " ".join(p.phonemes for p in parts))
            sf.write(hit, np.concatenate([np.asarray(p.audio) for p in parts]), RATE)
        audio, _ = sf.read(hit, dtype="float32")
        return audio

    return say


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: generate_story_audio.py <dossier-slug>")
    slug = sys.argv[1]
    folder = ROOT / "src" / "data" / "dossiers" / slug
    story = json.loads((folder / "story.json").read_text())
    langs = list(story["voices"])
    CACHE.mkdir(parents=True, exist_ok=True)
    say = {lang: synthesiser(story["voices"][lang]) for lang in langs}

    clips = {lang: [] for lang in langs}
    cues, scenes = {}, {}
    t, prev_scene = story["lead"], None
    for i, cue in enumerate(story["cues"]):
        if cue["scene"] != prev_scene:
            if prev_scene is not None:
                t += story["sceneGap"]
            scenes[cue["scene"]] = {"start": round(max(0.0, t - story["lead"] if i == 0 else t - 0.8), 2)}
            prev_scene = cue["scene"]
        else:
            t += story["gap"] + cue.get("pause", 0)
        lengths = {}
        for lang in langs:
            text = cue.get("say", {}).get(lang, cue[lang])
            audio = say[lang](text)
            clips[lang].append((t, audio))
            lengths[lang] = len(audio) / RATE
        end = t + max(lengths.values())
        cues[cue["id"]] = {"at": round(t, 2), "end": round(end, 2)}
        print(f"{t:6.1f}-{end:6.1f}  {cue['id']:<14} " + "  ".join(f"{l}:{lengths[l]:4.1f}s" for l in langs))
        t = end

    duration = round(t + story["tail"], 2)
    ids = [s["id"] for s in story["scenes"]]
    missing = [s for s in ids if s not in scenes]
    if missing:
        sys.exit(f"Scenes without cues: {missing}")
    for a, b in zip(ids, ids[1:]):
        scenes[a]["end"] = scenes[b]["start"]
    scenes[ids[-1]]["end"] = duration

    timing = {"$comment": "Generated by scripts/generate_story_audio.py from story.json. Do not edit.",
              "duration": duration, "scenes": {s: scenes[s] for s in ids}, "cues": cues}
    (folder / "story-timing.json").write_text(json.dumps(timing, indent=2, ensure_ascii=False) + "\n")

    out_dir = ROOT / "public" / "stories" / slug
    out_dir.mkdir(parents=True, exist_ok=True)
    for lang in langs:
        track = np.zeros(int(duration * RATE), dtype=np.float32)
        for start, audio in clips[lang]:
            first = int(start * RATE)
            track[first:first + len(audio)] += audio[: len(track) - first]
        wav = out_dir / f"narration-{lang}.wav"
        mp3 = wav.with_suffix(".mp3")
        sf.write(wav, track, RATE)
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav), "-ac", "1",
                        "-c:a", "libmp3lame", "-b:a", "64k", str(mp3)], check=True)
        wav.unlink()
        print(f"Wrote {mp3.relative_to(ROOT)} ({mp3.stat().st_size // 1024} KB)")
    print(f"Duration {duration:.1f}s — wrote {(folder / 'story-timing.json').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
